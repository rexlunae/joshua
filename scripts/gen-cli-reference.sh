#!/usr/bin/env bash
# Regenerate docs/cli-reference.md from the binary's own `--help` text, so the
# reference cannot drift from the flags.  Run from the repository root:
#
#   scripts/gen-cli-reference.sh            # default build
#   FEATURES=distributed scripts/gen-cli-reference.sh
#
# The environment is cleared while rendering so a JOSHUA_* variable set in the
# caller's shell does not show up as a "current value" in the reference.
set -euo pipefail

features=${FEATURES:-distributed}
out=docs/cli-reference.md

cargo build --release --quiet --features "$features" --bin joshua
bin=target/release/joshua
help() { env -i PATH="$PATH" COLUMNS=100 "$bin" "$@" --help; }

commands=$(help | awk '/^Commands:/{on=1; next} on && /^  [a-z]/{print $1} on && /^$/{exit}' | grep -v '^help$')

{
    echo "# CLI reference"
    echo
    echo "Generated by \`scripts/gen-cli-reference.sh\` from \`joshua --help\` (built"
    echo "with \`--features $features\`; commands marked *experimental* need that"
    echo "feature).  Every flag that has an \`[env: ...]\` line can also be set through"
    echo "that environment variable; an explicit flag wins over the variable."
    echo
    echo "\`serve\`, \`run\`, \`bench\` and \`ppl\` share one set of model-load flags"
    echo "(\`--n-ctx\`, \`--device\`, the page-cache, expert-cache, placement,"
    echo "speculative-decoding and NPU flags), so a benchmark or perplexity run loads"
    echo "the model exactly as the server would."
    echo
    echo '```text'
    help
    echo '```'
    for cmd in $commands; do
        echo
        echo "## \`joshua $cmd\`"
        echo
        echo '```text'
        help "$cmd"
        echo '```'
    done
} > "$out"
echo "wrote $out"
